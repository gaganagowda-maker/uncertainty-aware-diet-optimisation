    "# CELL 4: LP Solver — Baseline / Bertsimas-Sim Robust / Bonferroni CC\n",
    "\n",
    "def solve_lp(df_h, targets, k_min=20, gc=None, label='',\n",
    "             robust_dev=None, gamma_frac=None,\n",
    "             cc_alpha=None, cc_cv=None, time_limit=120):\n",
    "    \"\"\"\n",
    "    Diet LP/MILP (PuLP + CBC).\n",
    "\n",
    "    Mode 1 — Baseline LP:       No extra args.\n",
    "    Mode 2 — Bertsimas-Sim Robust:  robust_dev + gamma_frac\n",
    "    Mode 3 — Bonferroni CC LP:  cc_alpha + cc_cv\n",
    "\n",
    "    Returns: {'status', 'cost', 'plan' (DataFrame)}\n",
    "    \"\"\"\n",
    "    foods  = df_h['Food Name'].tolist()\n",
    "    n      = len(foods)\n",
    "    prices = dict(zip(foods, df_h['Price (£/100g)']))\n",
    "    min_x  = dict(zip(foods, df_h['min_x']))\n",
    "    max_x  = dict(zip(foods, df_h['max_x']))\n",
    "\n",
    "    prob = pulp.LpProblem(f\"Diet_{label}\", pulp.LpMinimize)\n",
    "    x    = pulp.LpVariable.dicts(\"x\", foods, lowBound=0)\n",
    "    y    = pulp.LpVariable.dicts(\"y\", foods, cat='Binary')\n",
    "\n",
    "    # Objective: minimise total food cost\n",
    "    prob += pulp.lpSum([prices[f] * x[f] for f in foods])\n",
    "\n",
    "    #  Nutrient constraints \n",
    "    if robust_dev is not None:\n",
    "        # Bertsimas-Sim Γ-budgeted robust counterpart\n",
    "        # Protects against at most Γ nutrient values deviating adversely.\n",
    "        # Reference: Bertsimas & Sim (2004), Operations Research.\n",
    "        Gamma = max(1, int(round(gamma_frac * n)))\n",
    "        for nut, b in targets.items():\n",
    "            nv = dict(zip(foods, df_h[nut]))\n",
    "            if b['min'] is not None:\n",
    "                z_v = pulp.LpVariable(f\"z_{nut[:8]}_{label}\", lowBound=0)\n",
    "                p_v = pulp.LpVariable.dicts(f\"p_{nut[:8]}_{label}\", foods, lowBound=0)\n",
    "                prob += (pulp.lpSum([nv[f] * x[f] for f in foods])\n",
    "                         - Gamma * z_v\n",
    "                         - pulp.lpSum([p_v[f] for f in foods])\n",
    "                         >= b['min'])\n",
    "                for f in foods:\n",
    "                    prob += z_v + p_v[f] >= robust_dev * nv[f] * x[f]\n",
    "            if b['max'] is not None:\n",
    "                prob += pulp.lpSum([nv[f] * x[f] for f in foods]) <= b['max']\n",
    "\n",
    "    elif cc_alpha is not None:\n",
    "        # Bonferroni approach - multiply each lower bound by a tightening factor\n",
    "        # so the plan still works even when nutrient values are slightly off.\n",
    "        # the maths comes from Charnes & Cooper (1963) - basically trades cost\n",
    "        # for reliability. turns out it is structurally infeasible for males\n",
    "        # because the male energy window is too narrow for the tightening.\n",
    "        factor = 1.0 - norm.ppf(cc_alpha) * cc_cv\n",
    "        if factor <= 0:\n",
    "            return {'status': 'InfeasibleByConstruction', 'cost': None, 'plan': None}\n",
    "        for nut, b in targets.items():\n",
    "            nv = dict(zip(foods, df_h[nut]))\n",
    "            if b['min'] is not None:\n",
    "                prob += factor * pulp.lpSum([nv[f] * x[f] for f in foods]) >= b['min']\n",
    "            if b['max'] is not None:\n",
    "                prob += pulp.lpSum([nv[f] * x[f] for f in foods]) <= b['max']\n",
    "\n",
    "    else:\n",
    "        # Baseline: nominal nutrient bounds\n",
    "        for nut, b in targets.items():\n",
    "            nv = dict(zip(foods, df_h[nut]))\n",
    "            if b['min'] is not None:\n",
    "                prob += pulp.lpSum([nv[f] * x[f] for f in foods]) >= b['min']\n",
    "            if b['max'] is not None:\n",
    "                prob += pulp.lpSum([nv[f] * x[f] for f in foods]) <= b['max']\n",
    "\n",
    "    #  Portion bounds (linked to binary y) \n",
    "    for f in foods:\n",
    "        prob += x[f] <= max_x[f] * y[f]\n",
    "        prob += x[f] >= min_x[f] * y[f]\n",
    "\n",
    "    #  Diversity: at least k_min distinct foods \n",
    "    prob += pulp.lpSum([y[f] for f in foods]) >= k_min\n",
    "\n",
    "    #  Eatwell: >=2 from Fruit/Veg/Grains; >=1 Dairy/PlantProtein \n",
    "    # Raised to 2 to prevent single-food exploitation (Maillot & Darmon 2010)\n",
    "    for g in ['Fruit', 'Vegetable', 'Grains']:\n",
    "        gf = df_h[df_h['Group'] == g]['Food Name'].tolist()\n",
    "        if gf:\n",
    "            prob += pulp.lpSum([y[f] for f in gf]) >= 2\n",
    "    for g in ['Dairy', 'PlantProtein']:\n",
    "        gf = df_h[df_h['Group'] == g]['Food Name'].tolist()\n",
    "        if gf:\n",
    "            prob += pulp.lpSum([y[f] for f in gf]) >= 1\n",
    "    prot_f = df_h[df_h['Group'].isin(['Meat','Fish','PlantProtein','Egg'])]['Food Name'].tolist()\n",
    "    if prot_f:\n",
    "        prob += pulp.lpSum([y[f] for f in prot_f]) >= 2\n",
    "\n",
    "    #  Volume cap: limit high-volume foods to 4x daily max per WEEK\n",
    "    # At weekly horizon (H=7): cap at 4 daily portions out of 7 possible.\n",
    "    # At monthly horizon: scale proportionally (cap at 4/7 fraction of monthly max).\n",
    "    # Prevents oats/bread from filling every meal slot. Ref: Benvenuti et al. (2020)\n",
    "    H_days = round(max_x.get(foods[0], 1) * 100 / GROUP_BOUNDS_DAILY.get(\n",
    "        df_h[df_h['Food Name']==foods[0]]['Group'].iloc[0] if foods else 'Vegetable',\n",
    "        (30,300))[1]) if foods else 1\n",
    "    # Use max_x (which is already scaled to horizon) / 7 * 4 to compute 4-day cap\n",
    "    for f in foods:\n",
    "        grp = df_h[df_h['Food Name']==f]['Group'].iloc[0]\n",
