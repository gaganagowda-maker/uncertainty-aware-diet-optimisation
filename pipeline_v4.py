    "# CELL 6: Monte Carlo Validator\n",
    "\n",
    "def monte_carlo(plan_df, df_master, targets_day,\n",
    "                n_sim=5000, cv=0.10, horizon_days=1, seed=42):\n",
    "    \"\"\"\n",
    "    stress-tests each plan by sampling nutrient values 5000 times from a\n",
    "    normal distribution around the reported mean. if the plan binds right\n",
    "    on the lower bound it will fail about half the time - that is what\n",
    "    shows the baseline is unreliable and the CC models actually help.\n",
    "\n",
    "    Returns DataFrame with columns: mean_daily, p5_daily, target, pct_meeting\n",
    "    \"\"\"\n",
    "    rng = np.random.default_rng(seed)\n",
    "    if plan_df is None or len(plan_df) == 0:\n",
    "        return None\n",
