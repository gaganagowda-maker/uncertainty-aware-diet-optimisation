    "# CELL 5: SOCP Solver — Exact Chance-Constrained (CVXPY)\n",
    "\n",
    "def solve_socp(df_h, targets, alpha=0.95, cv=0.10, gc=None, label=''):\n",
    "    \"\"\"\n",
    "    Exact SOCP deterministic equivalent (Charnes-Cooper 1963).\n",
    "\n",
    "    Under independent N(μ, cv·μ) nutrient coefficients:\n",
    "        P(Σ a_ji x_i ≥ b_j) ≥ α\n",
    "        ⟺  μ_j @ x − z_α · ‖diag(σ_j) x‖₂  ≥  b_j\n",
    "\n",
    "    This is a Second-Order Cone constraint, solved by ECOS/CLARABEL.\n",
    "    Less conservative than Bonferroni LP — always cheaper or equal cost.\n",
    "    Continuous relaxation (no binary variables).\n",
    "\n",
    "    Solver fallback: ECOS → CLARABEL → SCS.\n",
    "    \"\"\"\n",
    "    z_alpha = norm.ppf(alpha)\n",
    "    foods   = df_h['Food Name'].tolist()\n",
    "    prices  = np.array([float(df_h.loc[df_h['Food Name'] == f, 'Price (£/100g)'].iloc[0])\n",
    "                        for f in foods])\n",
    "    max_x   = np.array([float(df_h.loc[df_h['Food Name'] == f, 'max_x'].iloc[0])\n",
    "                        for f in foods])\n",
    "\n",
    "    x = cp.Variable(len(foods), nonneg=True)\n",
    "    constraints = [x <= max_x]\n",
    "\n",
    "    for nut, b in targets.items():\n",
    "        mu    = np.array([float(df_h.loc[df_h['Food Name'] == f, nut].iloc[0])\n",
    "                          for f in foods])\n",
    "        sigma = cv * mu          # σ_ji = cv · μ_ji\n",
    "        if b['min'] is not None:\n",
    "            # SOCP: μ^T x - z_α · ‖diag(σ) x‖₂ ≥ b_min\n",
    "            constraints += [\n",
    "                mu @ x - z_alpha * cp.norm(cp.multiply(sigma, x), 2) >= b['min']\n",
    "            ]\n",
    "        if b['max'] is not None:\n",
    "            constraints += [mu @ x <= b['max']]\n",
    "\n",
    "    # had to add this after noticing SOCP was coming out cheaper than the\n",
    "    # baseline LP which makes no sense for a more constrained model.\n",
    "    # the reason was SOCP has no binary variables so it could pick tiny\n",
    "    # amounts of everything without being forced to a minimum portion.\n",
    "    # forcing the cheapest food per group to its minimum fixes this -\n",
    "    # now SOCP is properly comparable. the remaining gap is the integrality gap.\n",
    "    required_groups = ['Fruit', 'Vegetable', 'Grains', 'Dairy', 'PlantProtein']\n",
    "    for g in required_groups:\n",
    "        g_df = df_h[df_h['Group'] == g]\n",
    "        if len(g_df) == 0:\n",
    "            continue\n",
    "        cheapest_food = g_df.loc[g_df['Price (£/100g)'].idxmin(), 'Food Name']\n",
    "        fp = foods.index(cheapest_food)\n",
    "        min_portion = float(df_h.loc[df_h['Food Name']==cheapest_food,'min_x'].iloc[0])\n",
    "        constraints += [x[fp] >= min_portion]\n",
    "\n",
    "    if gc is not None:\n",
    "        oi = [i for i, f in enumerate(foods)\n",
    "              if df_h.loc[df_h['Food Name'] == f, 'is_oily'].iloc[0]]\n",
    "        ri = [i for i, f in enumerate(foods)\n",
    "              if df_h.loc[df_h['Food Name'] == f, 'is_red_meat'].iloc[0]]\n",
    "        if ri:\n",
    "            constraints += [cp.sum(x[ri]) * 100 <= gc['red_meat_upper']]\n",
    "        if oi:\n",
    "            constraints += [cp.sum(x[oi]) * 100 >= gc['oily_fish_lower']]\n",
    "\n",
    "    prob = cp.Problem(cp.Minimize(prices @ x), constraints)\n",
    "\n",
    "    # ECOS was giving false-infeasible results in my Jupyter environment even\n",
    "    # when the problem was clearly solvable - switching to CLARABEL fixed it.\n",
    "    # kept ECOS first since it is fastest when it works, then falls back.\n",
    "    # this is the fix described in Section 7.2 of the dissertation.\n",
    "    for solver in [cp.ECOS, cp.CLARABEL, cp.SCS]:\n",
    "        try:\n",
    "            prob.solve(solver=solver, verbose=False)\n",
    "            if prob.status in ('optimal', 'optimal_inaccurate') and prob.value is not None:\n",
    "                break\n",
    "        except Exception:\n",
    "            continue\n",
    "\n",
    "    if prob.status not in ('optimal', 'optimal_inaccurate') or prob.value is None:\n",
    "        return {'status': prob.status, 'cost': None, 'plan': None}\n",
    "\n",
    "    plan = [{\n",
    "        'Food':     f,\n",
    "        'Group':    df_h.loc[df_h['Food Name'] == f, 'Group'].iloc[0],\n",
    "        'Grams':    round(float(x.value[i]) * 100, 1),\n",
    "        'Cost (£)': round(prices[i] * float(x.value[i]), 3),\n",
    "    } for i, f in enumerate(foods)\n",
    "      if x.value is not None and float(x.value[i]) > 1e-4]\n",
    "\n",
    "    return {\n",
    "        'status': prob.status,\n",
    "        'cost':   round(float(prob.value), 3),\n",
    "        'plan':   pd.DataFrame(plan).sort_values('Grams', ascending=False)\n",
    "                    .reset_index(drop=True)\n",
    "    }\n",
    "\n"
